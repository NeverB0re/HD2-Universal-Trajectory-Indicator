def generate(path):
    raw = Path(path).read_bytes()
    data = json.loads(raw)
    if data['build'] != 'F5FEE03DCFDB' or data['contract'] != 'hd2runtime.throwable.guarded_authoring.v1':
        raise ValueError('Review changed source build/contract before generating')
    kinds = {row['name']: row['kind'] for row in KINDS}
    rows = []
    for row in data['throwables']:
        if row['identity']['status'] != 'RESOLVED':
            raise ValueError('Unresolved identity: ' + row['name'])
        flight = next(t for t in row['targets'] if t['path'] == 'flight')
        fields = {f['semanticFieldId'].split('.', 1)[1]: f['baseline'] for f in flight['fields']}
        keys = ('launch_distance_min', 'launch_distance_max', 'launch_speed_override',
                'forward_strength_bonus', 'backward_strength_penalty')
        nums = ', '.join(format(fields[k], '.9g') for k in keys)
        rows.append("  ['%s'] = { %s, name = %s }," % (kinds[row['name']], nums, json.dumps(row['name'])))
    if len(rows) != 23 or len(kinds) != 23:
        raise ValueError('Review changed roster before generating')
    header = ("-- Generated by tools/generate_grenade_profiles.py; native launch calibration, not guaranteed range.\n"
              "-- Uses code / research from HD2Runtime by SkyeShade, https://github.com/SkyeShade/HD2Runtime\n"
              "-- Source a8c53396eb345c9fd79dae36a6f8564e85b4173a; build F5FEE03DCFDB.\n"
              "-- Capability JSON SHA256: %s\n"
              "-- { distance_min, distance_max, speed_override, forward_strength_bonus, backward_strength_penalty }\n"
              "-- Curve: speed^2 = 18 * (min + (max-min) * adjusted_strength). Caller strength needs calibration.\n") % hashlib.sha256(raw).hexdigest()
    # Caltrops are newer than this 23-item catalog. Upstream NarrowHUD's 14 throws support a 10m/s baseline;
    # mark it separately rather than pretending this item has a proven native row in the old catalog.
    rows.append("  ['2968deba6d6c2f09'] = { name = 'G-11 Caltrops', measured = 10 }, -- NarrowHUD 2.0.0")
    out = Path(__file__).resolve().parents[1] / 'src' / 'grenade_profiles.lua'
    out.write_text(header + 'return {\n' + '\n'.join(rows) + '\n}\n', encoding='utf-8', newline='\n')
    print('wrote', out, '(23 native profiles + separately measured Caltrops)')


if __name__ == '__main__':
    generate(sys.argv[1])
